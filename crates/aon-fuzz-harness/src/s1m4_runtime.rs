struct CyclicBytes<'a> {
    bytes: &'a [u8],
    cursor: usize,
}

impl<'a> CyclicBytes<'a> {
    const fn new(bytes: &'a [u8]) -> Self {
        Self { bytes, cursor: 0 }
    }

    fn next_u8(&mut self) -> u8 {
        if self.bytes.is_empty() {
            return 0;
        }
        let value = self.bytes[self.cursor % self.bytes.len()];
        self.cursor += 1;
        value
    }
}
