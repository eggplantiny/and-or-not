/// Maximum number of independent S1-M4 public-kernel cases generated by one invocation.
pub const MAX_S1M4_KERNEL_INPUT_BYTES: usize = 128;

/// Maximum number of stateful S1-M4 public-runtime scenarios generated by one invocation.
pub const MAX_S1M4_RUNTIME_INPUT_BYTES: usize = 12;

const WU: i64 = FIXED_ONE;
const CIRCUIT_PITCH: i64 = 16_384;
const ENEMY_RADIUS: i64 = 1_024;

#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub struct S1m4KernelCoverage {
    pub gate_work_cases: u64,
    pub junction_work_cases: u64,
    pub wire_work_cases: u64,
    pub substrate_work_cases: u64,
    pub redundant_vertex_checks: u64,
    pub strict_wire_growth_checks: u64,
    pub construction_progress_checks: u64,
    pub live_demand_cases: u64,
    pub live_final_ceil_cases: u64,
    pub contact_allocation_cases: u64,
    pub contact_remainder_cases: u64,
    pub contact_permutation_checks: u64,
    pub contact_conservation_checks: u64,
    pub heat_integration_cases: u64,
    pub damage_cases: u64,
    pub thermal_tie_checks: u64,
    pub order_rejection_checks: u64,
    pub numeric_boundary_checks: u64,
    pub command_tag8_checks: u64,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum S1m4KernelStage {
    Profile,
    ConstructionWork,
    ConstructionProgress,
    LiveDemand,
    ContactAllocation,
    HeatIntegration,
    Damage,
    Ordering,
    NumericBoundary,
    CommandEncoding,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum S1m4KernelInvariant {
    ProfileConstruction,
    WorkOracle,
    RedundantVertexIdentity,
    StrictWireGrowth,
    ProgressOracle,
    ProgressPermutation,
    LiveDemandOracle,
    ContactOracle,
    ContactPermutation,
    ContactConservation,
    HeatOracle,
    DamageOracle,
    ThermalTieToEven,
    TypedOrderingRejection,
    TypedNumericBoundary,
    CommandEncoderAgreement,
    CommandTag8,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum S1m4KernelExecutionObservation {
    KernelError {
        case_index: usize,
        stage: S1m4KernelStage,
    },
    InvariantViolation {
        case_index: usize,
        invariant: S1m4KernelInvariant,
    },
    Completed,
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct S1m4KernelObservation {
    pub consumed_len: usize,
    pub generated_cases: usize,
    pub coverage: S1m4KernelCoverage,
    pub execution: S1m4KernelExecutionObservation,
}

impl S1m4KernelObservation {
    pub const fn invariant_failure(&self) -> Option<&'static str> {
        match self.execution {
            S1m4KernelExecutionObservation::KernelError { .. } => {
                Some("bounded S1-M4 input produced a public-kernel error")
            }
            S1m4KernelExecutionObservation::InvariantViolation { .. } => {
                Some("S1-M4 public-kernel output disagreed with an independent invariant")
            }
            S1m4KernelExecutionObservation::Completed => None,
        }
    }
}

/// Exercises bounded exact S1-M4 kernels against independent integer oracles.
pub fn exercise_s1m4_kernels(input: &[u8]) -> S1m4KernelObservation {
    let bounded = &input[..input.len().min(MAX_S1M4_KERNEL_INPUT_BYTES)];
    let mut observation = S1m4KernelObservation {
        consumed_len: bounded.len(),
        generated_cases: 0,
        coverage: S1m4KernelCoverage::default(),
        execution: S1m4KernelExecutionObservation::Completed,
    };
    let mut cursor = CyclicBytes::new(bounded);

    for (case_index, selector) in bounded.iter().copied().enumerate() {
        let mut balance = BalanceProfile::construction_contact_damage_alpha("s1m4-fuzz");
        let Some(construction) = balance.construction_probe.as_mut() else {
            return finish_kernel_invariant(
                observation,
                case_index,
                S1m4KernelInvariant::ProfileConstruction,
            );
        };
        let Some(contact) = balance.contact_damage_probe.as_mut() else {
            return finish_kernel_invariant(
                observation,
                case_index,
                S1m4KernelInvariant::ProfileConstruction,
            );
        };
        let Some(work_coefficient) = bounded_ratio(
            i64::from(1 + cursor.next_u8() % 7),
            i64::from(1 + cursor.next_u8() % 9),
        ) else {
            return finish_kernel_invariant(
                observation,
                case_index,
                S1m4KernelInvariant::ProfileConstruction,
            );
        };
        let Some(live_coefficient) = bounded_ratio(
            i64::from(1 + cursor.next_u8() % 7),
            i64::from(1 + cursor.next_u8() % 11),
        ) else {
            return finish_kernel_invariant(
                observation,
                case_index,
                S1m4KernelInvariant::ProfileConstruction,
            );
        };
        construction.wire_work_per_ncu = work_coefficient;
        construction.substrate_work_per_square_wu = work_coefficient;
        contact.live_energy_per_strength_wu = live_coefficient;

        if let Err(invariant) = exercise_work_case(
            selector,
            &mut cursor,
            construction,
            &mut observation.coverage,
        ) {
            return finish_kernel_invariant(observation, case_index, invariant);
        }
        if let Err(invariant) =
            exercise_progress_case(selector, &mut cursor, &mut observation.coverage)
        {
            return finish_kernel_invariant(observation, case_index, invariant);
        }
        if let Err(invariant) =
            exercise_live_demand_case(selector, &mut cursor, contact, &mut observation.coverage)
        {
            return finish_kernel_invariant(observation, case_index, invariant);
        }
        if let Err(invariant) =
            exercise_contact_case(selector, &mut cursor, &mut observation.coverage)
        {
            return finish_kernel_invariant(observation, case_index, invariant);
        }
        if let Err(invariant) = exercise_heat_case(selector, &mut cursor, &mut observation.coverage)
        {
            return finish_kernel_invariant(observation, case_index, invariant);
        }
        if let Err(invariant) =
            exercise_damage_case(selector, &mut cursor, contact, &mut observation.coverage)
        {
            return finish_kernel_invariant(observation, case_index, invariant);
        }

        observation.generated_cases += 1;
    }

    if let Err(invariant) = exercise_negative_boundaries(&mut observation.coverage) {
        return finish_kernel_invariant(observation, bounded.len(), invariant);
    }
    if let Err(invariant) = exercise_command_tag8(&mut observation.coverage) {
        return finish_kernel_invariant(observation, bounded.len(), invariant);
    }
    observation
}

fn exercise_work_case(
    selector: u8,
    cursor: &mut CyclicBytes<'_>,
    probe: &aon_sim::ConstructionProbeProfile,
    coverage: &mut S1m4KernelCoverage,
) -> Result<(), S1m4KernelInvariant> {
    let target = match selector % 4 {
        0 => {
            coverage.gate_work_cases += 1;
            let gate_type = match cursor.next_u8() % 3 {
                0 => GateType::And,
                1 => GateType::Or,
                _ => GateType::Not,
            };
            ConstructionTarget::Gate {
                gate_type,
                origin: point(0, 0),
                routing_domain: RoutingDomain::OpenWorld,
            }
        }
        1 => {
            coverage.junction_work_cases += 1;
            ConstructionTarget::Junction {
                routing_domain: RoutingDomain::OpenWorld,
                position: point(0, 0),
            }
        }
        2 => {
            coverage.wire_work_cases += 1;
            let whole = 1 + i64::from(cursor.next_u8() % 31);
            ConstructionTarget::Wire {
                routing_domain: RoutingDomain::OpenWorld,
                points: vec![point(0, 0), point(whole * WU, 0)],
                endpoint_a: EndpointTarget::Free,
                endpoint_b: EndpointTarget::Free,
            }
        }
        _ => {
            coverage.substrate_work_cases += 1;
            let width = 1 + i64::from(cursor.next_u8() % 15);
            let height = 1 + i64::from(cursor.next_u8() % 15);
            ConstructionTarget::FixedSubstrate {
                origin: point(0, 0),
                routing_area: FixedAabb::new(point(0, 0), point(width * WU, height * WU)),
                footprint: FixedAabb::new(point(0, 0), point(width * WU, height * WU)),
            }
        }
    };
    let observed =
        required_construction_work(&target, probe).map_err(|_| S1m4KernelInvariant::WorkOracle)?;
    let expected =
        independent_work_oracle(&target, probe).ok_or(S1m4KernelInvariant::WorkOracle)?;
    if observed != expected {
        return Err(S1m4KernelInvariant::WorkOracle);
    }

    let reference = BalanceProfile::construction_contact_damage_alpha("s1m4-growth")
        .construction_probe
        .ok_or(S1m4KernelInvariant::ProfileConstruction)?;
    let short = wire_target(&[point(0, 0), point(WU, 0)]);
    let redundant = wire_target(&[point(0, 0), point(WU / 2, 0), point(WU, 0)]);
    let long = wire_target(&[point(0, 0), point(2 * WU, 0)]);
    let short_work = required_construction_work(&short, &reference)
        .map_err(|_| S1m4KernelInvariant::RedundantVertexIdentity)?;
    if required_construction_work(&redundant, &reference) != Ok(short_work) {
        return Err(S1m4KernelInvariant::RedundantVertexIdentity);
    }
    coverage.redundant_vertex_checks += 1;
    let long_work = required_construction_work(&long, &reference)
        .map_err(|_| S1m4KernelInvariant::StrictWireGrowth)?;
    if long_work <= short_work {
        return Err(S1m4KernelInvariant::StrictWireGrowth);
    }
    coverage.strict_wire_growth_checks += 1;
    Ok(())
}

fn exercise_progress_case(
    selector: u8,
    cursor: &mut CyclicBytes<'_>,
    coverage: &mut S1m4KernelCoverage,
) -> Result<(), S1m4KernelInvariant> {
    let required = 2 + u64::from(selector % 31);
    let completed = u64::from(cursor.next_u8()) % required;
    let site_id = ConstructionSiteId(EntityId(100));
    let base = ConstructionSite {
        id: site_id,
        target: ConstructionTarget::Junction {
            routing_domain: RoutingDomain::OpenWorld,
            position: point(0, 0),
        },
        required_work: Energy(required),
        completed_work: Energy(completed),
        activation_ready: false,
    };
    let first = ConstructionWorkContribution {
        site: site_id,
        builder: MobileId(EntityId(5)),
        granted_work: Energy(1 + u64::from(cursor.next_u8() % 17)),
    };
    let second = ConstructionWorkContribution {
        site: site_id,
        builder: MobileId(EntityId(2)),
        granted_work: Energy(1 + u64::from(cursor.next_u8() % 17)),
    };
    let mut forward = ConstructionSiteStore::new(vec![base.clone()])
        .map_err(|_| S1m4KernelInvariant::ProgressOracle)?;
    let mut reverse =
        ConstructionSiteStore::new(vec![base]).map_err(|_| S1m4KernelInvariant::ProgressOracle)?;
    let forward_rows = apply_construction_work(&mut forward, &[first, second])
        .map_err(|_| S1m4KernelInvariant::ProgressOracle)?;
    let reverse_rows = apply_construction_work(&mut reverse, &[second, first])
        .map_err(|_| S1m4KernelInvariant::ProgressOracle)?;
    if forward != reverse || forward_rows != reverse_rows {
        return Err(S1m4KernelInvariant::ProgressPermutation);
    }
    let mut remaining = required - completed;
    let mut expected_completed = completed;
    for row in &forward_rows {
        let applied = row.granted_work.0.min(remaining);
        remaining -= applied;
        expected_completed += applied;
        if row.applied_work != Energy(applied)
            || row.completed_work != Energy(expected_completed)
            || row.activation_ready != (remaining == 0)
        {
            return Err(S1m4KernelInvariant::ProgressOracle);
        }
    }
    coverage.construction_progress_checks += 1;
    Ok(())
}

fn exercise_live_demand_case(
    selector: u8,
    cursor: &mut CyclicBytes<'_>,
    probe: &aon_sim::ContactDamageProbeProfile,
    coverage: &mut S1m4KernelCoverage,
) -> Result<(), S1m4KernelInvariant> {
    let length = i64::from(1 + selector % 31) * (WU / 4);
    let strength = u128::from(1 + cursor.next_u8() % 63);
    let input = aon_sim::LiveWireInput {
        wire: WireId(EntityId(9)),
        length: Fixed(length),
        high_drive_strength: strength,
    };
    let observed = calculate_live_wire_demand(input, probe)
        .map_err(|_| S1m4KernelInvariant::LiveDemandOracle)?;
    let numerator = u128::try_from(probe.live_energy_per_strength_wu.numerator())
        .ok()
        .and_then(|coefficient| coefficient.checked_mul(strength))
        .and_then(|value| value.checked_mul(length as u128))
        .ok_or(S1m4KernelInvariant::LiveDemandOracle)?;
    let denominator = u128::try_from(probe.live_energy_per_strength_wu.denominator())
        .ok()
        .and_then(|coefficient| coefficient.checked_mul(WU as u128))
        .ok_or(S1m4KernelInvariant::LiveDemandOracle)?;
    let expected = ceil_div(numerator, denominator)
        .and_then(|value| u64::try_from(value).ok())
        .map(Energy)
        .ok_or(S1m4KernelInvariant::LiveDemandOracle)?;
    if observed != expected {
        return Err(S1m4KernelInvariant::LiveDemandOracle);
    }
    coverage.live_demand_cases += 1;
    if !numerator.is_multiple_of(denominator) {
        coverage.live_final_ceil_cases += 1;
    }
    Ok(())
}

fn exercise_contact_case(
    selector: u8,
    cursor: &mut CyclicBytes<'_>,
    coverage: &mut S1m4KernelCoverage,
) -> Result<(), S1m4KernelInvariant> {
    let grant = Energy(u64::from(selector));
    let leak = 1 + u64::from(cursor.next_u8() % 17);
    let candidate_count = 1 + usize::from(cursor.next_u8() % 4);
    let mut candidates = (0..candidate_count)
        .map(|index| ContactCandidate {
            target: EnemyId(EntityId(2 + u64::try_from(index).unwrap_or(0) * 3)),
            weight: u128::from(1 + cursor.next_u8() % 13),
        })
        .collect::<Vec<_>>();
    let observed = allocate_contact_energy(grant, &candidates, leak)
        .map_err(|_| S1m4KernelInvariant::ContactOracle)?;
    let expected = independent_contact_oracle(grant, &candidates, leak)
        .ok_or(S1m4KernelInvariant::ContactOracle)?;
    if observed != expected {
        return Err(S1m4KernelInvariant::ContactOracle);
    }
    candidates.reverse();
    if allocate_contact_energy(grant, &candidates, leak) != Ok(observed.clone()) {
        return Err(S1m4KernelInvariant::ContactPermutation);
    }
    let conserved = observed
        .0
        .iter()
        .try_fold(observed.1.0, |sum, row| sum.checked_add(row.absorbed.0));
    if conserved != Some(grant.0) {
        return Err(S1m4KernelInvariant::ContactConservation);
    }
    coverage.contact_allocation_cases += 1;
    coverage.contact_permutation_checks += 1;
    coverage.contact_conservation_checks += 1;
    let total_weight = candidates.iter().map(|row| row.weight).sum::<u128>();
    let denominator = u128::from(leak) + total_weight;
    let budget = u128::from(grant.0) * total_weight / denominator;
    let bases = candidates
        .iter()
        .map(|row| u128::from(grant.0) * row.weight / denominator)
        .sum::<u128>();
    if budget > bases {
        coverage.contact_remainder_cases += 1;
    }
    Ok(())
}

fn exercise_heat_case(
    selector: u8,
    cursor: &mut CyclicBytes<'_>,
    coverage: &mut S1m4KernelCoverage,
) -> Result<(), S1m4KernelInvariant> {
    let current = HeatEnergy(u64::from(selector));
    let count = 1 + usize::from(cursor.next_u8() % 4);
    let rows = (0..count)
        .map(|index| HeatContributionInput {
            key: HeatContributionKey {
                kind: match index {
                    0 => InteractionHeatKind::GatePowerDissipation,
                    1 => InteractionHeatKind::Movement,
                    2 => InteractionHeatKind::Construction,
                    _ => InteractionHeatKind::LiveWireRemainder,
                },
                source: EntityId(10 + u64::try_from(index).unwrap_or(0)),
                demand: None,
            },
            energy: HeatEnergy(1 + u64::from(cursor.next_u8() % 31)),
        })
        .collect::<Vec<_>>();
    let expected = rows
        .iter()
        .try_fold(current.0, |sum, row| sum.checked_add(row.energy.0))
        .map(HeatEnergy)
        .ok_or(S1m4KernelInvariant::HeatOracle)?;
    if integrate_heat(EntityId(1), current, &rows) != Ok(expected) {
        return Err(S1m4KernelInvariant::HeatOracle);
    }
    coverage.heat_integration_cases += 1;
    Ok(())
}

fn exercise_damage_case(
    selector: u8,
    cursor: &mut CyclicBytes<'_>,
    probe: &mut aon_sim::ContactDamageProbeProfile,
    coverage: &mut S1m4KernelCoverage,
) -> Result<(), S1m4KernelInvariant> {
    probe.electrical_tolerance.wire = 1 + u64::from(cursor.next_u8() % 13);
    probe.thermal_capacity.wire = 1 + u64::from(cursor.next_u8() % 13);
    probe.safe_temperature = Fixed(i64::from(cursor.next_u8() % 4) * WU);
    probe.thermal_damage_rate = bounded_ratio(
        i64::from(1 + cursor.next_u8() % 5),
        i64::from(1 + cursor.next_u8() % 7),
    )
    .ok_or(S1m4KernelInvariant::ProfileConstruction)?;
    let target = EntityId(50);
    let integrity = 1 + u64::from(cursor.next_u8() % 100);
    let temperature = i64::from(selector % 12) * (WU / 2);
    let count = 1 + usize::from(cursor.next_u8() % 4);
    let exposures = (0..count)
        .map(|index| ElectricalExposure {
            target,
            source: EntityId(2 + u64::try_from(index).unwrap_or(0)),
            energy: Energy(u64::from(cursor.next_u8() % 31)),
        })
        .collect::<Vec<_>>();
    let snapshot = DamageSnapshot {
        target,
        kind: ThermalObjectKind::Wire,
        integrity: Integrity(integrity),
        phase1_temperature: Fixed(temperature),
    };
    let observed = resolve_damage(snapshot, &exposures, probe)
        .map_err(|_| S1m4KernelInvariant::DamageOracle)?;
    let exposure = exposures.iter().map(|row| row.energy.0).sum::<u64>();
    let electrical = exposure / probe.electrical_tolerance.wire;
    let excess = temperature.saturating_sub(probe.safe_temperature.0).max(0) as u128;
    let thermal_n = u128::try_from(probe.thermal_damage_rate.numerator())
        .ok()
        .and_then(|value| value.checked_mul(excess))
        .ok_or(S1m4KernelInvariant::DamageOracle)?;
    let thermal_d = u128::try_from(probe.thermal_damage_rate.denominator())
        .ok()
        .and_then(|value| value.checked_mul(WU as u128))
        .ok_or(S1m4KernelInvariant::DamageOracle)?;
    let thermal = nearest_ties_even(thermal_n, thermal_d)
        .and_then(|value| u64::try_from(value).ok())
        .ok_or(S1m4KernelInvariant::DamageOracle)?;
    let total = electrical
        .checked_add(thermal)
        .ok_or(S1m4KernelInvariant::DamageOracle)?;
    let after = integrity.saturating_sub(total);
    if observed.electrical_exposure != Energy(exposure)
        || observed.electrical_damage != Integrity(electrical)
        || observed.thermal_damage != Integrity(thermal)
        || observed.integrity_after != Integrity(after)
        || observed.pending_destruction != (integrity > 0 && after == 0)
    {
        return Err(S1m4KernelInvariant::DamageOracle);
    }
    coverage.damage_cases += 1;

    let mut tie_probe = *probe;
    tie_probe.safe_temperature = Fixed::ZERO;
    tie_probe.thermal_damage_rate =
        Rational::new(1, 1).map_err(|_| S1m4KernelInvariant::ThermalTieToEven)?;
    let even = resolve_damage(
        DamageSnapshot {
            phase1_temperature: Fixed(WU / 2),
            integrity: Integrity(10),
            ..snapshot
        },
        &[],
        &tie_probe,
    )
    .map_err(|_| S1m4KernelInvariant::ThermalTieToEven)?;
    let odd = resolve_damage(
        DamageSnapshot {
            phase1_temperature: Fixed(WU + WU / 2),
            integrity: Integrity(10),
            ..snapshot
        },
        &[],
        &tie_probe,
    )
    .map_err(|_| S1m4KernelInvariant::ThermalTieToEven)?;
    if (even.thermal_damage, odd.thermal_damage) != (Integrity(0), Integrity(2)) {
        return Err(S1m4KernelInvariant::ThermalTieToEven);
    }
    coverage.thermal_tie_checks += 1;
    Ok(())
}

fn exercise_negative_boundaries(
    coverage: &mut S1m4KernelCoverage,
) -> Result<(), S1m4KernelInvariant> {
    let owner = EntityId(77);
    let low = HeatContributionInput {
        key: HeatContributionKey {
            kind: InteractionHeatKind::Movement,
            source: EntityId(2),
            demand: None,
        },
        energy: HeatEnergy(1),
    };
    let high = HeatContributionInput {
        key: HeatContributionKey {
            kind: InteractionHeatKind::Construction,
            source: EntityId(3),
            demand: None,
        },
        energy: HeatEnergy(1),
    };
    if integrate_heat(owner, HeatEnergy(0), &[high, low])
        != Err(ThermalDamageError::NonCanonicalHeatOrder { owner })
        || integrate_heat(owner, HeatEnergy(0), &[low, low])
            != Err(ThermalDamageError::DuplicateHeatContribution { owner })
    {
        return Err(S1m4KernelInvariant::TypedOrderingRejection);
    }

    let probe = BalanceProfile::construction_contact_damage_alpha("s1m4-boundaries")
        .contact_damage_probe
        .ok_or(S1m4KernelInvariant::ProfileConstruction)?;
    let target = EntityId(99);
    let snapshot = DamageSnapshot {
        target,
        kind: ThermalObjectKind::Wire,
        integrity: Integrity(10),
        phase1_temperature: Fixed::ZERO,
    };
    let earlier = ElectricalExposure {
        target,
        source: EntityId(2),
        energy: Energy(1),
    };
    let later = ElectricalExposure {
        target,
        source: EntityId(3),
        energy: Energy(1),
    };
    if resolve_damage(snapshot, &[later, earlier], &probe)
        != Err(ThermalDamageError::NonCanonicalExposureOrder)
        || !matches!(
            resolve_damage(snapshot, &[earlier, earlier], &probe),
            Err(ThermalDamageError::DuplicateExposureSource { .. })
        )
    {
        return Err(S1m4KernelInvariant::TypedOrderingRejection);
    }
    coverage.order_rejection_checks += 4;

    if integrate_heat(owner, HeatEnergy(u64::MAX), &[low])
        != Err(ThermalDamageError::ArithmeticOverflow)
    {
        return Err(S1m4KernelInvariant::TypedNumericBoundary);
    }
    let duplicate = ContactCandidate {
        target: EnemyId(EntityId(4)),
        weight: 1,
    };
    if !matches!(
        allocate_contact_energy(Energy(1), &[duplicate, duplicate], 1),
        Err(aon_sim::ContactError::DuplicateTarget { .. })
    ) || !matches!(
        allocate_contact_energy(
            Energy(u64::MAX),
            &[
                ContactCandidate {
                    target: EnemyId(EntityId(4)),
                    weight: u128::MAX,
                },
                ContactCandidate {
                    target: EnemyId(EntityId(5)),
                    weight: 1,
                },
            ],
            1,
        ),
        Err(aon_sim::ContactError::ArithmeticOverflow)
    ) {
        return Err(S1m4KernelInvariant::TypedNumericBoundary);
    }
    let mut invalid_probe = probe;
    invalid_probe.electrical_tolerance.wire = 0;
    if resolve_damage(snapshot, &[], &invalid_probe)
        != Err(ThermalDamageError::NonPositiveElectricalTolerance(
            ThermalObjectKind::Wire,
        ))
    {
        return Err(S1m4KernelInvariant::TypedNumericBoundary);
    }
    coverage.numeric_boundary_checks += 4;
    Ok(())
}

fn exercise_command_tag8(coverage: &mut S1m4KernelCoverage) -> Result<(), S1m4KernelInvariant> {
    let targets = [
        ConstructionTarget::Gate {
            gate_type: GateType::And,
            origin: point(0, 0),
            routing_domain: RoutingDomain::OpenWorld,
        },
        wire_target(&[point(0, 0), point(WU, 0)]),
        ConstructionTarget::Junction {
            routing_domain: RoutingDomain::OpenWorld,
            position: point(0, 0),
        },
        ConstructionTarget::FixedSubstrate {
            origin: point(0, 0),
            routing_area: FixedAabb::new(point(0, 0), point(WU, WU)),
            footprint: FixedAabb::new(point(0, 0), point(WU, WU)),
        },
    ];
    for (target_tag, target) in targets.into_iter().enumerate() {
        let envelope = CommandEnvelope {
            target_tick: Tick(7),
            ordinal: 11,
            command: Command::PlaceConstructionSite(PlaceConstructionSiteCommand { target }),
        };
        let allocated = envelope
            .canonical_bytes()
            .map_err(|_| S1m4KernelInvariant::CommandEncoderAgreement)?;
        let mut streamed = Vec::new();
        envelope
            .write_canonical(&mut |bytes| streamed.extend_from_slice(bytes))
            .map_err(|_| S1m4KernelInvariant::CommandEncoderAgreement)?;
        if allocated != streamed {
            return Err(S1m4KernelInvariant::CommandEncoderAgreement);
        }
        // Domain (15), encoder version (2), Tick (8), ordinal (8), then Command tag.
        if allocated.get(33) != Some(&8)
            || allocated.get(34) != u8::try_from(target_tag).ok().as_ref()
        {
            return Err(S1m4KernelInvariant::CommandTag8);
        }
        coverage.command_tag8_checks += 1;
    }
    Ok(())
}

fn independent_work_oracle(
    target: &ConstructionTarget,
    probe: &aon_sim::ConstructionProbeProfile,
) -> Option<Energy> {
    let value = match target {
        ConstructionTarget::Gate { gate_type, .. } => u128::from(match gate_type {
            GateType::And => probe.and_gate_work,
            GateType::Or => probe.or_gate_work,
            GateType::Not => probe.not_gate_work,
        }),
        ConstructionTarget::Junction { .. } => u128::from(probe.junction_base_work),
        ConstructionTarget::Wire { points, .. } => {
            let length = independent_axis_length(points)?;
            u128::from(probe.wire_endpoint_work).checked_add(rational_ceil(
                probe.wire_work_per_ncu,
                &[length],
                &[WU as u128],
            )?)?
        }
        ConstructionTarget::FixedSubstrate { footprint, .. } => {
            let width =
                u128::try_from(i128::from(footprint.max.x.0) - i128::from(footprint.min.x.0))
                    .ok()?;
            let height =
                u128::try_from(i128::from(footprint.max.y.0) - i128::from(footprint.min.y.0))
                    .ok()?;
            rational_ceil(
                probe.substrate_work_per_square_wu,
                &[width, height],
                &[WU as u128, WU as u128],
            )?
        }
    };
    u64::try_from(value).ok().map(Energy)
}

fn independent_axis_length(points: &[FixedVec2]) -> Option<u128> {
    if points.len() < 2 {
        return None;
    }
    points.windows(2).try_fold(0_u128, |sum, pair| {
        let dx = (i128::from(pair[1].x.0) - i128::from(pair[0].x.0)).unsigned_abs();
        let dy = (i128::from(pair[1].y.0) - i128::from(pair[0].y.0)).unsigned_abs();
        if dx != 0 && dy != 0 {
            return None;
        }
        sum.checked_add(dx + dy)
    })
}

fn rational_ceil(coefficient: Rational, factors: &[u128], divisors: &[u128]) -> Option<u128> {
    let numerator = factors.iter().try_fold(
        u128::try_from(coefficient.numerator()).ok()?,
        |value, factor| value.checked_mul(*factor),
    )?;
    let denominator = divisors.iter().try_fold(
        u128::try_from(coefficient.denominator()).ok()?,
        |value, factor| value.checked_mul(*factor),
    )?;
    ceil_div(numerator, denominator)
}

fn independent_contact_oracle(
    grant: Energy,
    candidates: &[ContactCandidate],
    leak: u64,
) -> Option<(Vec<ContactAllocation>, HeatEnergy)> {
    let mut candidates = candidates.to_vec();
    candidates.sort_unstable_by_key(|candidate| candidate.target);
    if grant.0 == 0 {
        return Some((Vec::new(), HeatEnergy(0)));
    }
    let total_weight = candidates
        .iter()
        .try_fold(0_u128, |sum, row| sum.checked_add(row.weight))?;
    let denominator = u128::from(leak).checked_add(total_weight)?;
    let target_budget = u128::from(grant.0).checked_mul(total_weight)? / denominator;
    let mut base_sum = 0_u128;
    let mut rows = candidates
        .into_iter()
        .map(|candidate| {
            let absorbed = u128::from(grant.0).checked_mul(candidate.weight)? / denominator;
            base_sum = base_sum.checked_add(absorbed)?;
            Some(ContactAllocation {
                target: candidate.target,
                weight: candidate.weight,
                absorbed: Energy(u64::try_from(absorbed).ok()?),
            })
        })
        .collect::<Option<Vec<_>>>()?;
    let remainder = usize::try_from(target_budget.checked_sub(base_sum)?).ok()?;
    for row in rows.iter_mut().take(remainder) {
        row.absorbed = row.absorbed.checked_add(Energy(1)).ok()?;
    }
    let absorbed = rows
        .iter()
        .try_fold(0_u64, |sum, row| sum.checked_add(row.absorbed.0))?;
    Some((rows, HeatEnergy(grant.0.checked_sub(absorbed)?)))
}

const fn ceil_div(numerator: u128, denominator: u128) -> Option<u128> {
    if denominator == 0 {
        return None;
    }
    let quotient = numerator / denominator;
    if numerator.is_multiple_of(denominator) {
        Some(quotient)
    } else {
        quotient.checked_add(1)
    }
}

fn nearest_ties_even(numerator: u128, denominator: u128) -> Option<u128> {
    if denominator == 0 {
        return None;
    }
    let quotient = numerator / denominator;
    let remainder = numerator % denominator;
    let doubled = remainder.checked_mul(2)?;
    if doubled < denominator || (doubled == denominator && quotient.is_multiple_of(2)) {
        Some(quotient)
    } else {
        quotient.checked_add(1)
    }
}

fn wire_target(points: &[FixedVec2]) -> ConstructionTarget {
    ConstructionTarget::Wire {
        routing_domain: RoutingDomain::OpenWorld,
        points: points.to_vec(),
        endpoint_a: EndpointTarget::Free,
        endpoint_b: EndpointTarget::Free,
    }
}

fn bounded_ratio(numerator: i64, denominator: i64) -> Option<Rational> {
    Rational::new(numerator, denominator).ok()
}

